('orders','politicas_financeiras'),
('orders','solicitacoes_estorno'),
('orders','FiscalAttachment'),
('orders','FiscalAttachmentAudit')
)
SELECT jsonb_build_object(
 'database',current_database(),
 'objects',(SELECT jsonb_agg(jsonb_build_object('schema',schema_name,'table',table_name,'exists',to_regclass(format('%I.%I',schema_name,table_name)) IS NOT NULL) ORDER BY schema_name,table_name) FROM expected),
 'columns',(SELECT jsonb_agg(jsonb_build_object('schema',table_schema,'table',table_name,'column',column_name,'type',udt_name) ORDER BY table_schema,table_name,ordinal_position) FROM information_schema.columns WHERE table_schema IN ('identity','sellers','catalog','orders')),
 'enums',(SELECT jsonb_agg(jsonb_build_object('schema',n.nspname,'type',t.typname,'value',e.enumlabel) ORDER BY n.nspname,t.typname,e.enumsortorder) FROM pg_enum e JOIN pg_type t ON t.oid=e.enumtypid JOIN pg_namespace n ON n.oid=t.typnamespace WHERE n.nspname IN ('identity','sellers','catalog','orders')),
 'migration_history_locations',(SELECT jsonb_agg(jsonb_build_object('schema',schemaname,'read_only_query',format('SELECT migration_name, checksum, finished_at, rolled_back_at FROM %I._prisma_migrations ORDER BY started_at;',schemaname))) FROM pg_tables WHERE tablename='_prisma_migrations' AND schemaname IN ('public','identity','sellers','catalog','orders'))
) AS marketplace_preflight;
