WITH expected(schema_name,table_name) AS (VALUES
('identity','usuarios'),
('identity','perfis_administrador'),
('identity','AdminAccessRole'),
('identity','AdminAccessGrant'),
('identity','AdminAccessAudit'),
('identity','AccountActionToken'),
('identity','Notification'),
('sellers','vendedores'),
('sellers','preferencias_pagamento'),
('sellers','PartnerDocumentType'),
('sellers','PartnerDocument'),
('sellers','PartnerReviewEvent'),
('sellers','seller_delivery_settings'),
('sellers','SellerNotificationJob'),
('catalog','produtos'),
('catalog','Activity'),
('catalog','ActivitySession'),
('catalog','Enrollment'),
('catalog','ActivityMaterial'),
('catalog','MaterialAccess'),
('catalog','eventos_analytics'),
('catalog','consentimentos_analytics'),
('catalog','ContactSubmission'),
